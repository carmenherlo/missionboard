"""Generate a theme export from a seed colour, without Material Theme Builder.

    python tools/generate_theme.py azul-mision --seed "#2458C3" --chroma 60
    python tools/build_theme.py azul-mision

Writes themes/<name>.json in Theme Builder's JSON format (light and dark
schemes), then build it with tools/build_theme.py as any other export.

The scheme is Material's standard one (Tonal Spot, 2021 spec: with the seed
of indigo it gives exactly Theme Builder's export), except for --chroma: the
intensity of the primary colour. Tonal Spot uses 36, which turns lively seeds
grey (indigo became lilac); azul-mision uses 60. Without --chroma the scheme is
Tonal Spot as is. Needs materialyoucolor (requirements-dev.txt).
"""

import argparse
import json
import re
from pathlib import Path

from materialyoucolor.dynamiccolor.dynamic_scheme import DynamicScheme
from materialyoucolor.dynamiccolor.material_dynamic_colors import MaterialDynamicColors
from materialyoucolor.dynamiccolor.variant import Variant
from materialyoucolor.hct import Hct
from materialyoucolor.palettes.tonal_palette import TonalPalette
from materialyoucolor.scheme.scheme_tonal_spot import SchemeTonalSpot

SOURCE_DIR = Path(__file__).resolve().parent.parent / "themes"

# The roles of a Theme Builder export, in its order
ROLES = (
    "primary surfaceTint onPrimary primaryContainer onPrimaryContainer secondary onSecondary"
    " secondaryContainer onSecondaryContainer tertiary onTertiary tertiaryContainer"
    " onTertiaryContainer error onError errorContainer onErrorContainer background onBackground"
    " surface onSurface surfaceVariant onSurfaceVariant outline outlineVariant shadow scrim"
    " inverseSurface inverseOnSurface inversePrimary primaryFixed onPrimaryFixed primaryFixedDim"
    " onPrimaryFixedVariant secondaryFixed onSecondaryFixed secondaryFixedDim"
    " onSecondaryFixedVariant tertiaryFixed onTertiaryFixed tertiaryFixedDim"
    " onTertiaryFixedVariant surfaceDim surfaceBright surfaceContainerLowest surfaceContainerLow"
    " surfaceContainer surfaceContainerHigh surfaceContainerHighest"
).split()


def scheme(seed: Hct, dark: bool, chroma: float | None) -> DynamicScheme:
    base = SchemeTonalSpot(seed, dark, 0.0, spec_version="2021")
    if chroma is None:
        return base
    return DynamicScheme(
        seed, Variant.TONAL_SPOT, 0.0, dark, spec_version="2021",
        primary_palette=TonalPalette.from_hue_and_chroma(seed.hue, chroma),
        secondary_palette=base.secondary_palette, tertiary_palette=base.tertiary_palette,
        neutral_palette=base.neutral_palette, neutral_variant_palette=base.neutral_variant_palette,
        error_palette=base.error_palette)


def main() -> None:
    parser = argparse.ArgumentParser(description="Write themes/<name>.json from a seed colour.")
    parser.add_argument("name")
    parser.add_argument("--seed", required=True, help='seed colour, e.g. "#2458C3"')
    parser.add_argument("--chroma", type=float, help="intensity of the primary colour (Tonal Spot: 36)")
    args = parser.parse_args()
    if not re.match(r"^#?[0-9a-fA-F]{6}$", args.seed):
        parser.error(f'--seed {args.seed}: a hex colour like "#2458C3"')
    seed_hex = "#" + args.seed.lstrip("#").upper()
    seed = Hct.from_int(0xFF000000 | int(seed_hex[1:], 16))
    colours = MaterialDynamicColors()
    schemes = {
        label: {role: f"#{getattr(colours, role).get_argb(scheme(seed, dark, args.chroma)) & 0xFFFFFF:06X}"
                for role in ROLES}
        for label, dark in (("light", False), ("dark", True))
    }
    variant = f"primary chroma {args.chroma:g}" if args.chroma is not None else "as is"
    export = {
        "description": f"Generated by tools/generate_theme.py: Tonal Spot (2021), {variant}.",
        "seed": seed_hex,
        "coreColors": {"primary": seed_hex},
        "extendedColors": [],
        "schemes": schemes,
    }
    path = SOURCE_DIR / f"{args.name}.json"
    path.write_text(json.dumps(export, indent=4) + "\n")
    print(f"wrote themes/{path.name}: primary {schemes['light']['primary']}")


if __name__ == "__main__":
    main()
